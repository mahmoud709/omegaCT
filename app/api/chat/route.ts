export async function POST(req: NextRequest) {
  const { messages } = await req.json();

  let projectsInfo = "";
  try {
    const projects = await prisma.project.findMany({
      select: { name: true, nameAr: true, details: true, detailsAr: true, location: true, locationAr: true, category: true, categoryAr: true }
    });
    
    if (projects.length > 0) {
      projectsInfo = projects.map(p => 
        `- المشروع: ${p.nameAr || p.name} (${p.categoryAr || p.category})\n  الموقع: ${p.locationAr || p.location}\n  التفاصيل: ${p.detailsAr || p.details}`
      ).join("\n\n");
    } else {
      projectsInfo = "لا توجد مشروعات مضافة حاليًا.";
    }
  } catch (error) {
    projectsInfo = "تعذر جلب المشروعات حاليًا.";
  }

  const dynamicPrompt = `${OMEGA_SYSTEM_PROMPT}\n\n═══════════════════════════════════════\nالمشروعات الحالية للشركة (من قاعدة البيانات):\n═══════════════════════════════════════\n${projectsInfo}\n\nاعتمد على هذه المشروعات للإجابة على أسئلة المستخدمين حول المشروعات الخاصة بالشركة.`;

  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    return new Response(
      JSON.stringify({ error: "GEMINI_API_KEY not configured" }),
      { status: 500, headers: { "Content-Type": "application/json" } }
    );
  }

  // Drop leading assistant messages — Gemini needs user-first turns
  type Msg = { role: string; content: string };
  let startIdx = 0;
  while (startIdx < messages.length && messages[startIdx].role !== "user") {
    startIdx++;
  }
  const trimmed: Msg[] = messages.slice(startIdx);

  if (trimmed.length === 0) {
    return new Response(
      JSON.stringify({ reply: "كيف يمكنني مساعدتك؟" }),
      { headers: { "Content-Type": "application/json" } }
    );
  }

  const contents = trimmed.map((m: Msg) => ({
    role: m.role === "user" ? "user" : "model",
    parts: [{ text: m.content }],
  }));

  const geminiRes = await fetch(
    `https://generativelanguage.googleapis.com/v1beta/models/gemini-3.5-flash-lite:streamGenerateContent?alt=sse&key=${apiKey}`,
    {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        system_instruction: { parts: [{ text: dynamicPrompt }] },
        contents,
        generationConfig: { temperature: 0.4, maxOutputTokens: 1200 },
      }),
    }
  );

  if (!geminiRes.ok) {
    const err = await geminiRes.text();
    return new Response(
      JSON.stringify({ error: `Gemini error: ${err}` }),
      { status: 500, headers: { "Content-Type": "application/json" } }
    );
  }

  // Stream SSE from Gemini → plain text stream to client
  const encoder = new TextEncoder();
  const stream = new ReadableStream({
    async start(controller) {
      const reader = geminiRes.body!.getReader();
      const decoder = new TextDecoder();
      let buffer = "";

      while (true) {
        const { done, value } = await reader.read();
        if (done) break;

        buffer += decoder.decode(value, { stream: true });
        const lines = buffer.split("\n");
        buffer = lines.pop() ?? "";

        for (const line of lines) {
          if (!line.startsWith("data: ")) continue;
          const json = line.slice(6).trim();
          if (json === "[DONE]") continue;
          try {
            const parsed = JSON.parse(json);
            const chunk =
              parsed?.candidates?.[0]?.content?.parts?.[0]?.text ?? "";
            if (chunk) {
              controller.enqueue(encoder.encode(chunk));
            }
          } catch {
            // ignore parse errors for partial chunks
          }
        }
      }
      controller.close();
    },
  });

  return new Response(stream, {
    headers: {
      "Content-Type": "text/plain; charset=utf-8",
      "X-Content-Type-Options": "nosniff",
    },
  });
}
